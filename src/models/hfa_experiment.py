"""Does down-weighting old seasons (a time-varying home edge) help?

CAUTION: this hypothesis was generated by looking at holdout betting diagnostics, so the
holdout numbers below are NOT a clean test; they motivate a forward test in the ledger.
"""

from __future__ import annotations

import numpy as np
import pandas as pd

from src.betting.run import load as load_betting
from src.betting.sim import place_bets
from src.features.ratings import RatingParams
from src.models.compare import attach_market, paired_bootstrap_delta, per_game_log_loss
from src.models.ratings_experiment import PRIMARY_FEATURES, TUNE_SEASONS, Context
from src.models.walk_forward import run_walk_forward


def main() -> None:
    ctx = Context()
    data = ctx.featurize(RatingParams(), use_qb=True)
    base = run_walk_forward(data, feature_set_name="b", feature_columns=PRIMARY_FEATURES)
    ref = base.set_index("game_id")

    print(f"{'training weights':<22}| dev 2002-16 vs base [95% CI] | holdout 2017-25 vs base [95% CI] | holdout bet ROI (flat, theta=0)")
    for half in (None, 8, 5, 3, 2):
        pred = base if half is None else run_walk_forward(data, feature_set_name="h", feature_columns=PRIMARY_FEATURES, half_life=half)
        cells = []
        for lo_s, hi_s in ((2002, 2016), (2017, 2025)):
            g = pred[pred.season.between(lo_s, hi_s)].set_index("game_id")
            y = g.home_win.astype(int).to_numpy()
            d, lo, hi = paired_bootstrap_delta(y, g.p_home_win.to_numpy(), ref.loc[g.index, "p_home_win"].to_numpy())
            cells.append(f"{d:+.4f} [{lo:+.4f},{hi:+.4f}]")

        bets = load_betting().drop(columns="p_home").merge(pred[["game_id", "p_home_win"]].rename(columns={"p_home_win": "p_home"}), on="game_id")
        b = place_bets(bets[bets.season.between(2017, 2025)], threshold=0.0, mode="flat")
        label = "all seasons equal" if half is None else f"half-life {half} seasons"
        print(f"{label:<22}| {cells[0]:<28} | {cells[1]:<32} | {b.ret.mean():+.3f}  (home bets {np.mean(b.side == 'home'):.0%})")

    m = attach_market(base, ctx.games)
    for lo_s, hi_s in ((2002, 2016), (2017, 2025)):
        s = m[m.season.between(lo_s, hi_s)]
        print(f"mean P(home) {lo_s}-{hi_s}: model {s.p_home_win.mean():.3f} | market {s.p_market.mean():.3f} | actual {s.home_win.mean():.3f}")
    s = m[m.season >= 2022]
    print(f"2022-2025: model {s.p_home_win.mean():.3f} | market {s.p_market.mean():.3f} | actual {s.home_win.mean():.3f}")


if __name__ == "__main__":
    main()
